export type IconName = keyof typeof PATHS;

/** `ic-bulb` ko'rinishidagi backend qiymatini ikonka nomiga aylantiradi. */
export function iconFromSlug(slug: string | undefined): IconName {
    if (!slug) return "spark";
    const name = slug.replace(/^ic-/, "").replace(/-([a-z])/g, (_, c: string) =>
        c.toUpperCase(),
    );
    return (name in PATHS ? name : "spark") as IconName;
}

type IconProps = {
    name: IconName;
    className?: string;
    /** Piksel yoki CSS o'lchov. Berilmasa `1em` — matn bilan birga o'sadi. */
    size?: number | string;
    strokeWidth?: number;
};

export function Icon({ name, className, size, strokeWidth = 1.7 }: IconProps) {
    const paths = PATHS[name].split("|");
    const dimension = size ?? "1em";

    return (
        <svg
            viewBox="0 0 24 24"
            width={dimension}
            height={dimension}
            fill="none"
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            strokeLinejoin="round"
            aria-hidden="true"
            className={cn("shrink-0", className)}
        >
            {paths.map((d) => (
                <path key={d} d={d} />
            ))}
        </svg>
    );
}
